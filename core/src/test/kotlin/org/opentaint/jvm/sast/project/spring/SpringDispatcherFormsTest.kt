/** These vectors use actual generated instructions and public interpreter forms. */
class SpringDispatcherFormsTest : BasicTestUtils() {
    override val sourceFileExtension = "java"
    private val cancellation by lazy { Cancellation().also { it.activate() } }
    private val manager by lazy { ApManager(cancellation, marks = MarkTable(FrozenMarkDeclarations(mapOf(
        "T" to FullKey(encodeGroup(MarkGroupKey.Model("T"), false), "T"),
    )))) }
    private val ops by lazy { ApOps(manager) }
    private val graph by lazy { JApplicationSingleExitGraph(JApplicationGraphImpl(cp, runBlocking { cp.usagesExt() })) }
    private val resolver by lazy { JIRCallResolver(cp, object : JIRUnitResolver {
        override fun resolve(method: JIRMethod) = UnknownUnit
        override fun locationIsUnknown(loc: RegisteredLocation) = true
    }) }
    private val interpreter by lazy {
        val entries = JIRMethodEntries(graph, JIRLanguageManager(cp), resolver, EmptyRules,
            JIRLocalAliasAnalysis.Params(useAliasAnalysis = false), cancellation, emptyMap())
        JIRInterpreter(manager, EmptyRules, JIRFactTypeChecker(cp), resolver,
            JIRMethodEntrypointResolver(graph), entries, null, null)
    }
    private val generated by lazy { generate(registry = true) }
    private val emptyRegistry by lazy { generate(registry = false) }
    private val t by lazy { MarkSlot.Concrete(manager.marks.mark("T")) }

    private data class Generated(val context: SpringWebProjectContext, val dispatcher: JIRMethod) {
        val dispatchers get() = context.controllerDispatcherMethods.filter {
            it.name.startsWith(GeneratedSpringControllerDispatcherDispatchMethod)
        }
        val cleanup get() = context.controllerDispatcherMethods.single {
            it.name == GeneratedSpringControllerDispatcherCleanupMethod
        } as SpringGeneratedMethod
    }

    private fun generate(registry: Boolean): Generated {
        val wrappers = listOf(findMethod(SAMPLE, "first"), findMethod(SAMPLE, "second"))
        val context = SpringWebProjectContext(wrappers.toSet(), cp)
        if (registry) {
            context.addComponent(findClass("$SAMPLE\$ZComponent"))
            context.addComponent(findClass("$SAMPLE\$AComponent"))
        }
        val generate = Class.forName("org.opentaint.jvm.sast.project.spring.SpringWebProjectKt")
            .getDeclaredMethod("generateDispatcher", SpringWebProjectContext::class.java, List::class.java)
        generate.isAccessible = true
        return Generated(context, generate.invoke(null, context, wrappers) as JIRMethod)
    }

    private fun key(method: JIRMethod) = MethodKey(EmptyMethodContext,
        method.instList.instructions.single { it is JMethodEnterInst })
    private fun cleanupCall(method: JIRMethod) = method.instList.instructions.single {
        it.callExpr?.method?.method?.name == GeneratedSpringControllerDispatcherCleanupMethod
    }
    private fun segment(method: JIRMethod): List<JIRInst> {
        val all = method.instList.instructions
        val cleanup = all.indexOf(cleanupCall(method))
        val fields = generated.context.componentRegistryField.size
        return all.subList(cleanup - fields, cleanup + fields + 1)
    }
    private fun fieldPath(ref: JIRFieldRef): List<Int> {
        val declaration = ref.field.field
        return listOf(manager.accessors.index(ClassStaticAccessor(declaration.enclosingClass.name)),
            manager.accessors.index(FieldAccessor(declaration.enclosingClass.name,
                declaration.name, declaration.type.typeName)))
    }
    private fun fact(base: AccessPathBase, path: List<Int>, tail: Tail = Tail.EXACT,
                     exclusion: ExclusionSet = ExclusionSet.Empty, demand: Boolean = tail == Tail.ANY,
                     mark: MarkSlot = t) = Conclusion(PathFact(base, path, tail, mark), exclusion, demand)

    @Test fun `every dispatcher saves sorted registry fields and restores paired fresh locals`(): Unit {
        val fields = generated.context.componentRegistryField.values.sortedBy { it.name }
        assertEquals(2, fields.size)
        assertEquals(2, generated.dispatchers.size)
        for (method in generated.dispatchers) {
            val segment = segment(method)
            val saves = segment.take(2).map { it as JIRAssignInst }
            val restores = segment.takeLast(2).map { it as JIRAssignInst }
            assertEquals(fields.map { it.field }, saves.map { (it.rhv as JIRFieldRef).field.field })
            assertEquals(fields.map { it.field }, restores.map { (it.lhv as JIRFieldRef).field.field })
            assertEquals(listOf(1, 2), saves.map { (it.lhv as JIRLocalVar).index })
            assertEquals(fields.map { "%reg_${it.name}" }, saves.map { (it.lhv as JIRLocalVar).name })
            assertEquals(saves.map { it.lhv }, restores.map { it.rhv })
            assertTrue(saves.all { (it.rhv as JIRFieldRef).instance == null })
            assertTrue(restores.all { (it.lhv as JIRFieldRef).instance == null })
        }
    }

    @Test fun `switch default and every controller block jump to the first save`(): Unit {
        for (method in generated.dispatchers) {
            val firstSave = segment(method).first().location.index
            val switch = method.instList.instructions.filterIsInstance<JIRSwitchInst>().single()
            assertEquals(firstSave, switch.default.index)
            val gotos = method.instList.instructions.filterIsInstance<JIRGotoInst>()
            assertEquals(switch.branches.size, gotos.size)
            assertTrue(gotos.all { it.target.index == firstSave })
        }
    }

    @Test fun `empty registry jumps directly to cleanup and needs no saved locals`(): Unit {
        assertTrue(emptyRegistry.context.componentRegistryField.isEmpty())
        for (method in emptyRegistry.dispatchers) {
            val cleanup = cleanupCall(method).location.index
            assertEquals(cleanup, method.instList.instructions.filterIsInstance<JIRSwitchInst>().single().default.index)
            assertTrue(method.instList.instructions.filterIsInstance<JIRGotoInst>().all { it.target.index == cleanup })
            assertTrue(method.instList.instructions.filterIsInstance<JIRAssignInst>()
                .none { (it.lhv as? JIRLocalVar)?.name?.startsWith("%reg_") == true })
        }
    }

    @Test fun `only cleanup has one whole static native cleaner`(): Unit {
        val cleaner = generated.cleanup.callCleaners.single()
        assertEquals(AccessPathBase.ClassStatic, cleaner.base)
        assertNull(cleaner.path)
        assertEquals(CleanReach.AT_AND_BELOW, cleaner.reach)
        assertNull(cleaner.mark)
        assertTrue(generated.context.controllerDispatcherMethods.filter { it !== generated.cleanup }
            .all { (it as SpringGeneratedMethod).callCleaners.isEmpty() })
    }

    @Test fun `generated methods own an unmodifiable cleaner list`(): Unit {
        val cleaner = Cleaner(AccessPathBase.ClassStatic, null, CleanReach.AT_AND_BELOW, null)
        val source = arrayListOf(cleaner)
        val method = SpringGeneratedMethod("owned", "void".typeName(),
            "()V", emptyList(), JIRInstListBuilder(), source)
        source.clear()
        assertEquals(listOf(cleaner), method.callCleaners)
        assertThrows(UnsupportedOperationException::class.java) { (method.callCleaners as MutableList<Cleaner>).clear() }
    }

    @Test fun `cleanup call wires native action in bound to added and touches static state`(): Unit {
        val method = generated.dispatcher
        val call = cleanupCall(method)
        val plan = interpreter.callPlan(key(method), call, checkNotNull(call.callExpr))
        assertEquals(setOf(AccessPathBase.ClassStatic), plan.touched)
        val action = plan.stages.filterIsInstance<CallStage.Actions>().single {
            it.from == CallPoint.BOUND && it.to == CallPoint.ADDED
        }
        val cleaner = (action.steps.single() as CleanStep.Clean).cleaner
        assertSame(generated.cleanup.callCleaners.single(), cleaner)
        assertTrue(plan.passReads.isEmpty())
        assertTrue(plan.sinks.isEmpty())
    }

    @Test fun `fact free cleanup removes all static kinds and layers without requests`(): Unit {
        val method = generated.dispatcher
        val call = cleanupCall(method)
        val p = fieldPath((segment(method).first() as JIRAssignInst).rhv as JIRFieldRef)
        val suffix = manager.accessors.index(FieldAccessor(SAMPLE, "extra", "java.lang.Object"))
        val inputs = listOf(
            fact(AccessPathBase.ClassStatic, p), fact(AccessPathBase.ClassStatic, p, Tail.ANY),
            fact(AccessPathBase.ClassStatic, p, Tail.ANY_TAINT, ExclusionSet.of(suffix)),
            fact(AccessPathBase.ClassStatic, emptyList(), Tail.STAR, mark = MarkSlot.STAR),
            fact(AccessPathBase.ClassStatic, p, Tail.STAR, ExclusionSet.of(suffix), mark = MarkSlot.STAR))
        for (input in inputs) assertTrue(runCleanup(method, call, setOf(input)).isEmpty(), input.toString())
    }

    @Test fun `cleanup passes locals and zero while backward cleanup removes static requirements`(): Unit {
        val method = generated.dispatcher
        val call = cleanupCall(method)
        val local = fact(AccessPathBase.LocalVar(100), emptyList())
        val zero = Conclusion(ZERO_FACT, ExclusionSet.Empty, false)
        assertEquals(setOf(local, zero), runCleanup(method, call, setOf(local, zero)))
        val plan = interpreter.forms(key(method)).call(Direction.BACKWARD, call, checkNotNull(call.callExpr))
        val input = fact(AccessPathBase.ClassStatic, emptyList(), Tail.ANY)
        assertTrue(runPlan(plan, call, setOf(input), Direction.BACKWARD).isEmpty())
    }

    @Test fun `save cleanup restore preserves registry content and removes other static content`(): Unit {
        val method = generated.dispatcher
        val segment = segment(method)
        val save = segment.first() as JIRAssignInst
        val prefix = fieldPath(save.rhv as JIRFieldRef)
        val component = generated.context.componentRegistryField.entries.sortedBy { it.value.name }.first().key
        val value = manager.accessors.index(FieldAccessor(component.name, "value", "java.lang.Object"))
        val other = manager.accessors.index(ClassStaticAccessor(SAMPLE))
        val outside = manager.accessors.index(FieldAccessor(SAMPLE, "outside", "java.lang.Object"))
        for (input in listOf(fact(AccessPathBase.ClassStatic, prefix + value),
            fact(AccessPathBase.ClassStatic, prefix, Tail.ANY),
            fact(AccessPathBase.ClassStatic, prefix, Tail.ANY_TAINT, ExclusionSet.of(value)))) {
            // Excluded-field preservation is a later-run strong-transfer property.
            // Run-1 has empty field exclusions and demotes affected transfers.
            val result = runSegment(method, segment, setOf(input,
                fact(AccessPathBase.ClassStatic, listOf(other, outside))), run1 = false)
            assertEquals(setOf(input), result.filter { it.fact.base == AccessPathBase.ClassStatic }.toSet())
            assertTrue(result.any { it.fact.base == AccessPathBase.LocalVar(1) })
        }
    }

    @Test fun `a bare registry class fact is cleaned and is not restored by field saves`(): Unit {
        val method = generated.dispatcher
        val prefix = fieldPath((segment(method).first() as JIRAssignInst).rhv as JIRFieldRef)
        val input = fact(AccessPathBase.ClassStatic, prefix.take(1))
        assertTrue(runSegment(method, segment(method), setOf(input)).isEmpty())
    }

    @Test fun `old Spring provider stays fact based and excludes the registry from cleanup`(): Unit {
        val method = generated.cleanup
        val statement = method.instList.instructions.first()
        val rules = SpringRuleProvider(EmptyRules, generated.context)
        assertTrue(rules.cleanerRulesForMethod(method, statement, null).none())
        val old = TreeApManager(object : AnyAccessorUnrollStrategy {
            override fun unrollAccessor(accessor: Accessor) = false
        }, RefManager(), cancellation)
        val other = ClassStaticAccessor(SAMPLE)
        val registry = ClassStaticAccessor(GeneratedSpringRegistry)
        val outsideFact = old.createFinalAp(AccessPathBase.ClassStatic,
            org.opentaint.dataflow.ap.ifds.ExclusionSet.Empty).prependAccessor(other)
        val registryFact = old.createFinalAp(AccessPathBase.ClassStatic,
            org.opentaint.dataflow.ap.ifds.ExclusionSet.Empty).prependAccessor(registry)
        val cleaner = rules.cleanerRulesForMethod(method, statement, outsideFact).single()
        assertEquals(listOf(RemoveAllMarks(ClassStatic(SAMPLE))), cleaner.actionsAfter)
        assertTrue(rules.cleanerRulesForMethod(method, statement, registryFact).none())
    }

    @Test fun `generated dispatch instructions retain boundary and generated location contracts`(): Unit {
        for (method in generated.context.controllerDispatcherMethods) {
            val all = method.instList.instructions
            assertTrue(all[all.size - 3] is JMethodEnterInst)
            assertTrue(all[all.size - 2] is JMethodExitNormalInst)
            assertTrue(all.last() is JMethodExitExceptionalInst)
            assertTrue(all.all { it.location.method == method })
            assertTrue(all.all { it.lineNumber == -1 })
            assertTrue(all.none { it.callExpr?.method?.method?.isClassInitializer == true })
        }
    }

    private fun runSegment(method: JIRMethod, segment: List<JIRInst>, inputs: Set<Conclusion>,
                           run1: Boolean = true): Set<Conclusion> {
        var current = inputs
        val reference = FormsReference(ops, ReferenceAlgebra(
            ApMode(run1, Direction.FORWARD, Int.MAX_VALUE), manager = manager))
        for (statement in segment) current = if (statement.callExpr != null) runCleanup(method, statement, current, run1)
        else current.flatMap { input -> reference.apply(FormsReference.Mode.STATEMENT,
            interpreter.statementSummary(key(method), statement), setOf(ZERO_PATTERN), input,
            Place(statement, statementEdge = true, sources = false)) }.toSet()
        return current
    }
    private fun runCleanup(method: JIRMethod, call: JIRInst, inputs: Set<Conclusion>, run1: Boolean = true) =
        runPlan(interpreter.callPlan(key(method), call, checkNotNull(call.callExpr)), call, inputs, Direction.FORWARD, run1)
    private fun runPlan(plan: CallPlan, call: JIRInst, inputs: Set<Conclusion>, direction: Direction,
                        run1: Boolean = direction == Direction.FORWARD): Set<Conclusion> {
        val reference = FormsReference(ops, ReferenceAlgebra(ApMode(run1, direction, 1), manager = manager))
        return reference.run(plan, inputs.map { input ->
            val premise = when {
                direction == Direction.BACKWARD && input.fact != ZERO_FACT -> Pattern(input.fact, input.exclusion)
                input.fact.mark is MarkSlot.Star -> Pattern(PathFact(input.fact.base, emptyList(), Tail.STAR,
                    MarkSlot.STAR), ExclusionSet.Empty)
                else -> ZERO_PATTERN
            }
            PlanItem(setOf(premise), input, null)
        },
            Place(call, statementEdge = false, sources = false), PlanHooks(guards = true,
                clean = { cleaner, item ->
                    val output = cleanRes(cleaner, item.c)
                    assertNull(output.request)
                    output.facts.map { item.copy(c = it) }
                })).filter { it.first == plan.exit }.map { it.second.c }.toSet()
    }

    private companion object { const val SAMPLE = "test.samples.bidi.SpringBidiSample" }
}

private object EmptyRules : TaintRulesProvider {
    override val markDeclarations = RawMarkDeclarations.EMPTY
    override fun entryPointRulesForMethod(method: CommonMethod, statement: CommonInst, fact: FactAp?, allRelevant: Boolean) = emptyList<TaintEntryPointSource>()
    override fun sourceRulesForMethod(method: CommonMethod, statement: CommonInst, fact: FactAp?, allRelevant: Boolean) = emptyList<TaintMethodSource>()
    override fun exitSourceRulesForMethod(method: CommonMethod, statement: CommonInst, fact: FactAp?, allRelevant: Boolean) = emptyList<TaintMethodExitSource>()
    override fun sinkRulesForMethod(method: CommonMethod, statement: CommonInst, fact: FactAp?, allRelevant: Boolean) = emptyList<TaintMethodSink>()
    override fun sinkRulesForMethodEntry(method: CommonMethod, statement: CommonInst, fact: FactAp?, allRelevant: Boolean) = emptyList<TaintMethodEntrySink>()
    override fun sinkRulesForMethodExit(method: CommonMethod, statement: CommonInst, fact: FactAp?, initialFacts: Set<InitialFactAp>?, allRelevant: Boolean) = emptyList<TaintMethodExitSink>()
    override fun passTroughRulesForMethod(method: CommonMethod, statement: CommonInst?, fact: FactAp?, allRelevant: Boolean) = emptyList<TaintPassThrough>()
    override fun cleanerRulesForMethod(method: CommonMethod, statement: CommonInst, fact: FactAp?, allRelevant: Boolean) = emptyList<TaintCleaner>()
    override fun sourceRulesForStaticField(field: JIRField, statement: CommonInst, fact: FactAp?, allRelevant: Boolean) = emptyList<TaintStaticFieldSource>()
    override fun selectRules(ruleIds: Set<String>) = Unit
}
