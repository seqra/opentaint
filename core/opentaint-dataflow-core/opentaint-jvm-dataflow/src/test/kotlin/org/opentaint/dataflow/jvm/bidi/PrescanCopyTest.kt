/** Copy from real prescan owners; expected targets come from the generated bytecode classes. */
class PrescanCopyTest : BidiJIRTestUtils() {
    private fun testContext(exact: Boolean): MethodContext = JIRArgumentTypeMethodContext(1,
        TypeConstraintInfo(checkNotNull(cp.findClassOrNull("java.lang.Object")), exact))

    @Test
    fun `rule ids copy accepted serialized prescan rules without retaining the manager set`(): Unit {
        val callee = method("target", JIRPrescanFixtures.SAMPLE)
        val sources = arrayListOf(
            TaintMethodSource(callee, mkTrue(), emptyList(), null, "source-A"),
            TaintMethodSource(callee, mkFalse(), emptyList(), null, "false-source"),
            TaintMethodSource(callee, mkTrue(), emptyList(), null, null),
        )
        val pass = TaintPassThrough(callee, mkTrue(), listOf(CopyAllMarks(Argument(0), Result)), null, "pass-B")
        val rules = object : TaintRulesProvider by NoTaintRules {
            override fun sourceRulesForMethod(method: CommonMethod, statement: CommonInst, fact: FactAp?,
                allRelevant: Boolean): Iterable<TaintMethodSource> = if (method == callee) sources else emptyList()
            override fun passTroughRulesForMethod(method: CommonMethod, statement: CommonInst?, fact: FactAp?,
                allRelevant: Boolean): Iterable<TaintPassThrough> = if (method == callee) listOf(pass) else emptyList()
        }
        JIRPrescanFixtures(cp, graph, rules).use { f ->
            f.run("normal")
            f.engine.requirePrescanJoined()
            val caller = f.method("ruleCalls")
            val s = caller.instList.instructions.single { it.callExpr?.method?.method == callee }
            val call = checkNotNull(s.callExpr)
            val ctx = f.context(caller)
            assertTrue(ctx.taint.sourceRulesForCallStatement(s, call, null, null).isEmpty(),
                "Prescan records source ids but does not execute a source")
            assertEquals(listOf(pass), ctx.taint.passRulesForCallStatement(s, call, null, null).map { it.rule })
            val saved = f.manager.prescanRuleIds()
            assertEquals(setOf("source-A", "pass-B"), saved)
            sources += TaintMethodSource(callee, mkTrue(), emptyList(), null, "source-C")
            ctx.taint.sourceRulesForCallStatement(s, call, null, null)
            assertEquals(setOf("source-A", "pass-B"), saved)
            assertEquals(setOf("source-A", "pass-B", "source-C"), f.manager.prescanRuleIds())
            f.manager.releasePrescan()
            f.engine.releasePrescan()
            assertEquals(setOf("source-A", "pass-B"), saved)
        }
    }

    @Test
    fun `lambda export unions context targets by method and index but separates other callers and indexes`(): Unit {
        JIRPrescanFixtures(cp, graph).use { f ->
            f.run("normal")
            val caller = f.method("invoke")
            val other = f.method("invokeOther")
            val index = f.call(caller).location.index
            val otherIndex = f.call(other).location.index
            val declared = checkNotNull(f.call(caller).callExpr).method.method
            val first = f.context(caller, testContext(false))
            val second = f.context(caller, testContext(true))
            first.lambdaCallResolution.put(index, JIRLambdaTracker.LambdaTracker(declared).also {
                it.addLambda(f.lambda("first")); it.addLambda(f.lambda("first"))
            })
            second.lambdaCallResolution.put(index, JIRLambdaTracker.LambdaTracker(declared).also {
                it.addLambda(f.lambda("second"))
            })
            f.context(other).lambdaCallResolution.put(otherIndex, JIRLambdaTracker.LambdaTracker(declared).also {
                it.addLambda(f.lambda("first"))
            })
            val twoSites = f.method("twoSites")
            val sites = twoSites.instList.instructions.filter { it.callExpr?.method?.method?.name == "apply" }
            assertEquals(2, sites.size)
            val twice = f.context(twoSites)
            for ((site, allocation) in sites.zip(listOf("first", "second")))
                twice.lambdaCallResolution.put(site.location.index, JIRLambdaTracker.LambdaTracker(declared).also {
                    it.addLambda(f.lambda(allocation))
                })
            val saved = f.manager.prescanLambdas()
            assertEquals(setOf(f.implementation("first"), f.implementation("second")), saved.getValue(caller)[index])
            assertEquals(setOf(f.implementation("first")), saved.getValue(other)[otherIndex])
            assertEquals(setOf(f.implementation("first")), saved.getValue(twoSites)[sites[0].location.index])
            assertEquals(setOf(f.implementation("second")), saved.getValue(twoSites)[sites[1].location.index])
            first.lambdaCallResolution[index]!!.addLambda(f.lambda("second"))
            second.lambdaCallResolution.clear()
            assertEquals(setOf(f.implementation("first"), f.implementation("second")), saved.getValue(caller)[index])
        }
    }

    @Test
    fun `enumerating prescan lambda values does not subscribe a callback to later resolutions`(): Unit {
        JIRPrescanFixtures(cp, graph).use { f ->
            f.run("normal")
            val caller = f.method("invoke")
            val s = f.call(caller)
            val tracker = JIRLambdaTracker.LambdaTracker(checkNotNull(s.callExpr).method.method)
            tracker.addLambda(f.lambda("first"))
            val ctx = f.context(caller)
            ctx.lambdaCallResolution.put(s.location.index, tracker)
            val saved = f.manager.prescanLambdas()
            assertEquals(setOf(f.implementation("first")), saved.getValue(caller)[s.location.index])
            tracker.addLambda(f.lambda("second"))
            assertEquals(setOf(f.implementation("first")), saved.getValue(caller)[s.location.index])
            assertEquals(setOf(f.implementation("first"), f.implementation("second")),
                f.manager.prescanLambdas().getValue(caller)[s.location.index])
            f.manager.selectPhase(TaintAnalysisManager.Phase.FullScan)
            assertEquals(setOf(f.implementation("first"), f.implementation("second")),
                f.manager.prescanLambdas().getValue(caller)[s.location.index],
                "The existing phase reset removes subscriptions, not registered lambda values")
        }
    }

    @Test
    fun `mutating an exported collection cannot change a fresh manager export`(): Unit {
        JIRPrescanFixtures(cp, graph).use { f ->
            f.run("normal")
            val caller = f.method("invoke")
            val s = f.call(caller)
            val tracker = JIRLambdaTracker.LambdaTracker(checkNotNull(s.callExpr).method.method)
            tracker.addLambda(f.lambda("first"))
            f.context(caller).lambdaCallResolution.put(s.location.index, tracker)
            fun unchanged() = assertEquals(setOf(f.implementation("first")),
                f.manager.prescanLambdas().getValue(caller)[s.location.index])
            val targets = f.manager.prescanLambdas().getValue(caller)[s.location.index]!!
            mutateOrImmutable { (targets as MutableSet<JIRMethod>).clear() }; unchanged()
            val primitive = f.manager.prescanLambdas().getValue(caller)
            mutateOrImmutable { primitive.int2ObjectEntrySet().single().setValue(emptySet()) }; unchanged()
            val generic: MutableMap<Int, Set<JIRMethod>> = f.manager.prescanLambdas().getValue(caller)
            mutateOrImmutable { generic.entries.single().setValue(emptySet()) }; unchanged()
            val outer = f.manager.prescanLambdas()
            @Suppress("UNCHECKED_CAST")
            mutateOrImmutable { (outer as MutableMap<JIRMethod, Int2ObjectMap<Set<JIRMethod>>>).clear() }; unchanged()
        }
    }

    @Test
    fun `real prescan discovers both lambda implementations at the shared call site`(): Unit {
        JIRPrescanFixtures(cp, graph).use { f ->
            f.run("rootFirst", "rootSecond")
            assertEquals(org.opentaint.dataflow.ap.ifds.TaintAnalysisUnitRunnerManager.Status.OK, f.engine.status.get())
            f.engine.requirePrescanJoined()
            val caller = f.method("invoke")
            val index = f.call(caller).location.index
            val saved = f.manager.prescanLambdas()
            assertEquals(setOf(f.implementation("first"), f.implementation("second")), saved.getValue(caller)[index])
            assertTrue(f.contexts().any { it.methodEntryPoint.method == caller }, "Actual prescan visited the shared body")
            f.manager.releasePrescan()
            f.engine.releasePrescan()
            assertTrue(f.contexts().isEmpty())
            val owner = interp(prescanLambdas = saved)
            val s = f.call(caller)
            val firstKey = key(caller, testContext(false))
            val secondKey = key(caller, testContext(true))
            val p = owner.forms(firstKey).call(Direction.FORWARD, s, checkNotNull(s.callExpr))
            assertEquals(setOf(f.implementation("first"), f.implementation("second")),
                p.stages.filterIsInstance<CallStage.Callees>().single().callees.map { it.method }.toSet())
            assertSame(p, owner.forms(firstKey).call(Direction.FORWARD, s, checkNotNull(s.callExpr)))
            assertNotSame(p, owner.forms(secondKey).call(Direction.FORWARD, s, checkNotNull(s.callExpr)))
            assertSame(owner.entries[firstKey], owner.entries[secondKey], "The method-level frozen union is shared")
            val unknown = f.method("invokeOther")
            val missing = f.call(unknown)
            val unresolved = owner.forms(key(unknown)).call(Direction.FORWARD, missing, checkNotNull(missing.callExpr))
            assertTrue(unresolved.stages.filterIsInstance<CallStage.Edges>().any { it.kind == StageKind.UNRESOLVED })
        }
    }

    @Test
    fun `empty prescan exports are owned and release requires no artificial method state`(): Unit {
        JIRPrescanFixtures(cp, graph).use { f ->
            f.run()
            f.engine.requirePrescanJoined()
            assertTrue(f.manager.prescanRuleIds().isEmpty())
            assertTrue(f.manager.prescanLambdas().isEmpty())
            f.manager.releasePrescan()
            f.engine.releasePrescan()
            assertTrue(f.engine.allUnits().isEmpty())
            assertFailsWith<IllegalStateException> { f.engine.apManager }
        }
    }

    private inline fun mutateOrImmutable(body: () -> Unit) {
        try { body() } catch (_: UnsupportedOperationException) { }
    }
}
